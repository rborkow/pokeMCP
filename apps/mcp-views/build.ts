/**
 * Build every view into one HTML file and write the Worker module that
 * bundles them: src/connector/views/view-html.ts (generated, committed).
 *
 * Each view's resource URI carries a hash of its HTML, so a host that cached
 * an older view never pairs it with a newer tool result. A view over the size
 * budget fails the build.
 *
 * Usage (from apps/mcp-views): bun run build
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { build } from "vite";

/**
 * Gzipped bytes allowed per view. Hosts fetch the HTML for each conversation.
 * About 65 KB of it is the MCP Apps SDK's own runtime (its message schemas
 * are zod), which every view carries; the rest is the view.
 */
const BUDGET_GZIP_BYTES = 100 * 1024;
const OUT_MODULE = "../../src/connector/views/view-html.ts";

const views = readdirSync("src/views", { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

const built: { name: string; hash: string; html: string }[] = [];
for (const name of views) {
    process.env.VIEW = name;
    await build({ configFile: "vite.config.ts", logLevel: "error" });
    const html = readFileSync(`dist/${name}/index.html`, "utf8");
    const gzip = gzipSync(html).length;
    if (gzip > BUDGET_GZIP_BYTES) {
        throw new Error(
            `View ${name} is ${gzip} bytes gzipped, over the ${BUDGET_GZIP_BYTES}-byte budget`,
        );
    }
    const hash = createHash("sha256").update(html).digest("hex").slice(0, 12);
    built.push({ name, hash, html });
    console.log(`${name}: ${html.length} bytes, ${gzip} gzipped, hash ${hash}`);
}

const body = built
    .map(
        (view) =>
            `    ${JSON.stringify(view.name)}: {\n` +
            `        hash: ${JSON.stringify(view.hash)},\n` +
            `        html: ${JSON.stringify(view.html)},\n` +
            "    },",
    )
    .join("\n");

writeFileSync(
    OUT_MODULE,
    "// Generated by apps/mcp-views/build.ts (`bun run build:views`). Do not edit.\n" +
        "// Each view is one self-contained HTML document served at a ui:// resource.\n\n" +
        `export const VIEW_HTML = {\n${body}\n} as const;\n\n` +
        "export type ViewName = keyof typeof VIEW_HTML;\n",
);
console.log(`Wrote ${OUT_MODULE}`);
