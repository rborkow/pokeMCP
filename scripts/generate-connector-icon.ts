/**
 * Regenerate every copy of the VGC Teambuilder connector icon from its one
 * source, apps/teambuilder/public/vgc-teambuilder-icon.svg:
 *
 *   apps/teambuilder/public/vgc-teambuilder-icon.png   512px, for listings that take an image URL
 *   src/favicon-data.ts                                the SVG and a multi-size .ico, bundled into
 *                                                      the worker and served at api.pokemcp.com
 *
 * The worker serves the icon itself because directories show the favicon of
 * the MCP server's own domain, and the site and the worker share no files.
 *
 * Usage: bun run generate-connector-icon
 */
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { initWasm, Resvg } from "@resvg/resvg-wasm";

const SOURCE = "apps/teambuilder/public/vgc-teambuilder-icon.svg";
const SITE_PNG = "apps/teambuilder/public/vgc-teambuilder-icon.png";
const WORKER_MODULE = "src/favicon-data.ts";
const SITE_PNG_SIZE = 512;
/** Sizes packed into favicon.ico. 256 is the largest an .ico entry can describe. */
const ICO_SIZES = [16, 32, 48, 64, 128, 256];

function renderPng(svg: string, size: number): Uint8Array {
    return new Resvg(svg, { fitTo: { mode: "width", value: size } }).render().asPng();
}

/** Pack PNG images into an .ico container (PNG-encoded entries). */
export function buildIco(images: { size: number; png: Uint8Array }[]): Uint8Array {
    const headerSize = 6 + images.length * 16;
    const total = headerSize + images.reduce((sum, image) => sum + image.png.length, 0);
    const ico = new Uint8Array(total);
    const view = new DataView(ico.buffer);
    view.setUint16(0, 0, true); // reserved
    view.setUint16(2, 1, true); // type: icon
    view.setUint16(4, images.length, true);

    let offset = headerSize;
    images.forEach((image, index) => {
        const entry = 6 + index * 16;
        // Width and height are one byte each; 0 means 256.
        view.setUint8(entry, image.size === 256 ? 0 : image.size);
        view.setUint8(entry + 1, image.size === 256 ? 0 : image.size);
        view.setUint8(entry + 2, 0); // no palette
        view.setUint8(entry + 3, 0); // reserved
        view.setUint16(entry + 4, 1, true); // colour planes
        view.setUint16(entry + 6, 32, true); // bits per pixel
        view.setUint32(entry + 8, image.png.length, true);
        view.setUint32(entry + 12, offset, true);
        ico.set(image.png, offset);
        offset += image.png.length;
    });
    return ico;
}

async function main() {
    const require = createRequire(import.meta.url);
    await initWasm(await readFile(require.resolve("@resvg/resvg-wasm/index_bg.wasm")));

    const svg = (await readFile(SOURCE, "utf8")).trim();

    await writeFile(SITE_PNG, renderPng(svg, SITE_PNG_SIZE));

    const ico = buildIco(ICO_SIZES.map((size) => ({ size, png: renderPng(svg, size) })));
    const base64 = Buffer.from(ico).toString("base64");
    const lines: string[] = base64.match(/.{1,96}/g) ?? [];
    // Written the way Biome formats it, so regenerating leaves no formatting diff.
    const svgLiteral = `'${svg.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n")}'`;
    const module = `// Generated by scripts/generate-connector-icon.ts from
// ${SOURCE}. Do not edit by hand.

/** The connector icon as SVG. */
export const FAVICON_SVG =
    ${svgLiteral};

/** The connector icon as a base64 .ico holding ${ICO_SIZES.join(", ")} pixel images. */
export const FAVICON_ICO_BASE64 =
${lines.map((line) => `    "${line}"`).join(" +\n")};
`;
    await writeFile(WORKER_MODULE, module);

    console.log(`Wrote ${SITE_PNG} (${SITE_PNG_SIZE}px)`);
    console.log(`Wrote ${WORKER_MODULE} (.ico ${ico.length} bytes, sizes ${ICO_SIZES.join("/")})`);
}

main().catch((error) => {
    console.error(error);
    process.exit(1);
});
